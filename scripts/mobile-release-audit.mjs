import fs from 'node:fs'
const checks=[]
const ok=(name,pass,detail='')=>checks.push({name,pass,detail})
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'))
const cfg=fs.readFileSync('scripts/write-mobile-config.mjs','utf8')
const native=fs.readFileSync('src/mobile/nativePlatform.ts','utf8')
const client=fs.readFileSync('src/ClientPortal.tsx','utf8')
const app=fs.readFileSync('src/App.tsx','utf8')
const pushDispatch=fs.readFileSync('supabase/functions/mobile-push-dispatch/index.ts','utf8')
const nativeBackground=fs.readFileSync('src/mobile/nativeBackgroundLocation.ts','utf8')
const target=fs.readFileSync('src/mobile/mobileTarget.ts','utf8')
const main=fs.readFileSync('src/main.tsx','utf8')
const html=fs.readFileSync('index.html','utf8')
const pushRepo=fs.readFileSync('src/mobile/pushTokenRepository.ts','utf8')
const pushMigration=fs.readFileSync('supabase/migrations/20261010141000_mobile_push_token_registry.sql','utf8')
ok('Client bundle ID',cfg.includes('com.copilotsecurity.client'))
ok('Guard bundle ID',cfg.includes('com.copilotsecurity.guard'))
ok('Guard legacy bridge enabled',cfg.includes("useLegacyBridge: ${target==='guard'?'true':'false'}"))
ok('Guard native HTTP enabled',cfg.includes("CapacitorHttp: { enabled: ${target==='guard'?'true':'false'} }"))
ok('Client/Guard role isolation',target.includes("role==='client'")&&target.includes("role==='guard'"))
ok('Native product title isolation',target.includes("document.title=target==='guard'?'CO PILOT GUARD':'CO PILOT SECURITY'")&&main.includes('configureMobileDocument()'))
ok('Native safe-area viewport enabled',html.includes('viewport-fit=cover'))
ok('No production remote server URL',!cfg.includes('server: { url:')&&!cfg.includes('server:{url:'))
ok('Native camera adapter',native.includes('Camera.getPhoto'))
ok('Native foreground GPS adapter',native.includes('Geolocation.getCurrentPosition'))
ok('Native push token capture',native.includes("addListener('registration'"))
ok('Native push action capture',native.includes("pushNotificationActionPerformed")&&native.includes('co-pilot-native-push-action'))
ok('Native push action job routing data',native.includes('job_id')&&native.includes('jobId'))
ok('Client notification tap opens activity',client.includes("consumeStoredNativePushAction('client')")&&client.includes("setSection('activity')"))
ok('Guard notification tap refreshes mission',app.includes("consumeStoredNativePushAction('guard')")&&app.includes('nativePushJobId'))
ok('Capacitor camera dependency',Boolean(pkg.dependencies?.['@capacitor/camera']))
ok('Capacitor geolocation dependency',Boolean(pkg.dependencies?.['@capacitor/geolocation']))
ok('Capacitor push dependency',Boolean(pkg.dependencies?.['@capacitor/push-notifications']))
ok('Background geolocation dependency',Boolean(pkg.dependencies?.['@capacitor-community/background-geolocation']))
ok('Android notification permission dependency',Boolean(pkg.dependencies?.['@capacitor/local-notifications']))
ok('Android background notification permission gate',nativeBackground.includes('LocalNotifications.checkPermissions')&&nativeBackground.includes('LocalNotifications.requestPermissions'))
ok('Native Guard background location adapter',nativeBackground.includes('BackgroundGeolocation.addWatcher')&&nativeBackground.includes('publishGuardLocation'))
ok('Guard app selects native background location',app.includes("mobileTarget()==='guard'")&&app.includes('startNativeGuardBackgroundLocation'))
ok('Push token persistence RPC',pushRepo.includes('register_mobile_push_token'))
ok('Push registry requires authenticated user',pushMigration.includes('auth.uid() is null'))
ok('Push registry enforces app role',pushMigration.includes('APP_ROLE_MISMATCH'))
ok('Push token table not directly exposed',pushMigration.includes('revoke all on public.mobile_push_tokens from public, anon, authenticated'))
ok('Push RPC execute restricted',pushMigration.includes('revoke execute on function public.register_mobile_push_token(text,text,text) from public, anon'))
ok('Push registration independent of mission state',app.includes("auth.phase!=='ready'||!auth.user||!roleAllowedForMobile(auth.role)"))
ok('Push dispatch requires platform admin',pushDispatch.includes("role!=='platform_admin'"))
ok('Push dispatch uses registered mobile tokens',pushDispatch.includes("from('mobile_push_tokens')"))
ok('Push dispatch includes mission deep-link payload',pushDispatch.includes('job_id:n.job_id'))
ok('Push dispatch supports APNs and FCM',pushDispatch.includes('sendApns')&&pushDispatch.includes('sendFcm'))
const failed=checks.filter(c=>!c.pass)
for(const c of checks)console.log(`${c.pass?'PASS':'FAIL'}  ${c.name}`)
console.log(`\n${checks.length-failed.length}/${checks.length} mobile source release checks passed.`)
if(failed.length)process.exit(1)
